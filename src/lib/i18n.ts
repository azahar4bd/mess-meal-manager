const BN_RE = /[ঀ-৿]/;

/** বাংলা ফ্রেজ ইংরেজিতে — মিল না পেলে হুবহু ফেরত */
export function tr(text: string): string {
  if (!text || !BN_RE.test(text)) return text;
  const hit = BN_TO_EN[text.trim()];
  if (hit !== undefined) {
    // আগে/পরে whitespace/নতুন লাইন সংরক্ষণ
    const lead = text.match(/^\s*/)?.[0] ?? "";
    const tail = text.match(/\s*$/)?.[0] ?? "";
    return `${lead}${hit}${tail}`;
  }
  return text;
}
