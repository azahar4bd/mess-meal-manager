export interface BazarItemSuggestion {
  name: string;
  group: string;
}

export const BAZAR_ITEMS: BazarItemSuggestion[] = Object.entries(GROUPS).flatMap(([group, list]) =>
  list
    .split(",")
    .map((x) => x.trim())
    .filter(Boolean)
    .map((name) => ({ name, group })),
);

const ALL_NAMES = BAZAR_ITEMS.map((i) => i.name);

/**
 * টাইপ করা অক্ষর থেকে মিল খোঁজে — প্রথমে শুরুতে মিল, তারপর ভেতরে মিল।
 * বাংলা/ইংরেজি দুটোতেই কাজ করে; সর্বোচ্চ `limit`টি ফেরত দেয়।
 */
export function suggestBazarItems(query: string, limit = 8): BazarItemSuggestion[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const byName = new Map(BAZAR_ITEMS.map((i) => [i.name, i]));
  const starts: BazarItemSuggestion[] = [];
  const contains: BazarItemSuggestion[] = [];
  for (const name of ALL_NAMES) {
    const n = name.toLowerCase();
    const hit = byName.get(name);
    if (!hit) continue;
    if (n.startsWith(q)) starts.push(hit);
    else if (n.includes(q)) contains.push(hit);
  }
  return [...starts, ...contains].slice(0, limit);
}

/** পুরো তালিকা (গ্রুপ সহ) — এডিটর/গাইডে দেখানোর জন্য */
export function bazarItemGroups(): { group: string; items: string[] }[] {
  return Object.entries(GROUPS).map(([group, list]) => ({
    group,
    items: list.split(",").map((x) => x.trim()).filter(Boolean),
  }));
}
